import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { createReadStream, createWriteStream } from 'fs';
import { mkdir, unlink, access, stat } from 'fs/promises';
import { dirname, join } from 'path';
import { Readable } from 'stream';
import { pipeline } from 'stream/promises';
import { createHash } from 'crypto';
import { ByteRange, StorageAdapter, WriteResult } from './storage-adapter.interface';

/**
 * Content is stored under `<root>/<first 2 chars of pointer>/<pointer>` so a
 * single directory never accumulates millions of files (a cheap stand-in for
 * the sharding a real content-addressed store would do). `pointer` itself is
 * generated by ObjectsService/MultipartService — this adapter just persists
 * whatever pointer it's given.
 */
@Injectable()
export class LocalDiskStorageAdapter implements StorageAdapter {
  private readonly logger = new Logger(LocalDiskStorageAdapter.name);
  private readonly root: string;

  constructor(private readonly config: ConfigService) {
    this.root = this.config.get<string>('storage.localRoot') || './data/blobs';
  }

  async write(pointer: string, stream: Readable): Promise<WriteResult> {
    const path = this.resolvePath(pointer);
    await mkdir(dirname(path), { recursive: true });

    const hash = createHash('md5');
    let size = 0;
    stream.on('data', (chunk: Buffer) => {
      hash.update(chunk);
      size += chunk.length;
    });

    await pipeline(stream, createWriteStream(path));

    return { size, checksum: hash.digest('hex') };
  }

  async read(pointer: string, range?: ByteRange): Promise<Readable> {
    const path = this.resolvePath(pointer);
    return createReadStream(path, range ? { start: range.start, end: range.end } : undefined);
  }

  async delete(pointer: string): Promise<void> {
    const path = this.resolvePath(pointer);
    try {
      await unlink(path);
    } catch (err: any) {
      if (err.code !== 'ENOENT') throw err;
    }
  }

  async exists(pointer: string): Promise<boolean> {
    try {
      await access(this.resolvePath(pointer));
      return true;
    } catch {
      return false;
    }
  }

  async concatenate(pointers: string[], destinationPointer: string): Promise<WriteResult> {
    const destPath = this.resolvePath(destinationPointer);
    await mkdir(dirname(destPath), { recursive: true });

    const hash = createHash('md5');
    let size = 0;
    const destStream = createWriteStream(destPath);

    for (const pointer of pointers) {
      const srcPath = this.resolvePath(pointer);
      const partStat = await stat(srcPath);
      size += partStat.size;

      await new Promise<void>((resolve, reject) => {
        const src = createReadStream(srcPath);
        src.on('data', (chunk: Buffer) => hash.update(chunk));
        src.on('error', reject);
        src.on('end', resolve);
        src.pipe(destStream, { end: false });
      });
    }

    await new Promise<void>((resolve) => destStream.end(resolve));

    this.logger.log(`Concatenated ${pointers.length} parts into ${destinationPointer}`);
    return { size, checksum: hash.digest('hex') };
  }

  private resolvePath(pointer: string): string {
    const shard = pointer.slice(0, 2) || '00';
    return join(this.root, shard, pointer);
  }
}
